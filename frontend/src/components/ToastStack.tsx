export type ToastIconName = keyof typeof TOAST_ICONS;

interface ToastProps {
  tone: ToastTone;
  icon: ToastIconName;
  onDismiss: () => void;
  autoHideMs?: number;
  children: React.ReactNode | ((requestClose: () => void) => React.ReactNode);
}

export const Toast: React.FC<ToastProps> = ({ tone, icon, onDismiss, autoHideMs, children }) => {
  const [leaving, setLeaving] = useState(false);
  const onDismissRef = useRef(onDismiss);
  onDismissRef.current = onDismiss;

  const requestClose = () => {
    setLeaving(true);
  };

  useEffect(() => {
    if (!autoHideMs || leaving) return;
    const timeout = window.setTimeout(requestClose, autoHideMs);
    return () => window.clearTimeout(timeout);
  }, [autoHideMs, leaving]);

  useEffect(() => {
    if (!leaving) return;
    const timeout = window.setTimeout(() => onDismissRef.current(), 400);
    return () => window.clearTimeout(timeout);
  }, [leaving]);

  const handleAnimationEnd = (event: React.AnimationEvent<HTMLDivElement>) => {
    if (event.target !== event.currentTarget) return;
    if (leaving && event.animationName === 'toast-out') onDismiss();
  };

  return (
    <div
      className={`app__toast-slot${leaving ? ' app__toast-slot--leaving' : ''}`}
      onAnimationEnd={handleAnimationEnd}
    >
      <div className="app__toast-slot-inner">
        <div className={`app__toast app__toast--${tone}`} role="status">
          <div className="app__toast-content">
            <svg
              className="app__toast-icon"
              xmlns="http://www.w3.org/2000/svg"
              viewBox="0 0 256 256"
              width="20"
              height="20"
              fill="currentColor"
              aria-hidden="true"
              focusable="false"
            >
              <path d={TOAST_ICONS[icon]} />
            </svg>
            <div className="app__toast-body">
              {typeof children === 'function' ? children(requestClose) : children}
            </div>
          </div>
          {autoHideMs == null && tone !== 'version' && (
            <button type="button" className="app__toast-close" onClick={requestClose}>
              Close
            </button>
          )}
        </div>
      </div>
    </div>
  );
};

export const ToastStack: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  return <div className="app__toasts">{children}</div>;
};
